/**
 * Compliance Audit PDF HTML template.
 */
import { escapeHtml } from "./download";
import type {
  ComplianceAnalysis,
  ComplianceGap,
} from "@/features/compliance/types";

const STATUS_COLORS: Record<string, string> = {
  COVERED: "#16a34a",
  PARTIAL: "#d97706",
  NOT_ADDRESSED: "#dc2626",
};

const STATUS_LABELS: Record<string, string> = {
  COVERED: "Covered",
  PARTIAL: "Partial",
  NOT_ADDRESSED: "Gap",
};

function statusBadge(status: string): string {
  const color = STATUS_COLORS[status] ?? "#6b7280";
  const label = STATUS_LABELS[status] ?? status;
  return `<span style="display:inline-block;padding:2px 8px;border-radius:4px;font-size:11px;font-weight:600;color:#fff;background:${color}">${escapeHtml(label)}</span>`;
}

function gapRow(gap: ComplianceGap): string {
  return `
    <tr style="border-bottom:1px solid #e5e7eb">
      <td style="padding:8px 12px;font-family:monospace;font-size:12px">${escapeHtml(gap.controlId)}</td>
      <td style="padding:8px 12px;font-size:13px">${escapeHtml(gap.controlName)}</td>
      <td style="padding:8px 12px">${statusBadge(gap.status)}</td>
      <td style="padding:8px 12px;font-size:12px;color:#6b7280">${(gap.recommendedActions ?? []).map((a) => `• ${escapeHtml(a)}`).join("<br>")}</td>
    </tr>`;
}

export function generateCompliancePDFHTML(
  modelName: string,
  orgName: string,
  framework: string,
  analysis: ComplianceAnalysis,
): string {
  const now = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const covered = analysis.coveredControls ?? 0;
  const partial = analysis.partialControls ?? 0;
  const total = analysis.totalControls ?? 0;
  const gaps = analysis.gaps ?? [];
  const gapCount = gaps.filter((g) => g.status === "NOT_ADDRESSED").length;
  const score = analysis.coveragePercentage ?? 0;

  const criticalGaps = gaps.filter((g) => g.status === "NOT_ADDRESSED");
  const partialGaps = gaps.filter((g) => g.status === "PARTIAL");

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Compliance Audit Report — ${escapeHtml(framework)}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; color: #1f2937; background: #fff; }
    .cover { page-break-after: always; padding: 60px 48px; min-height: 100vh; display: flex; flex-direction: column; justify-content: center; border-bottom: 4px solid #1e40af; }
    .cover-tag { font-size: 11px; font-weight: 700; letter-spacing: 2px; text-transform: uppercase; color: #6b7280; margin-bottom: 24px; }
    .cover-title { font-size: 36px; font-weight: 800; color: #111827; line-height: 1.2; margin-bottom: 8px; }
    .cover-subtitle { font-size: 20px; color: #374151; margin-bottom: 40px; }
    .cover-meta { font-size: 14px; color: #6b7280; line-height: 2; }
    .section { padding: 40px 48px; page-break-inside: avoid; }
    .section-title { font-size: 18px; font-weight: 700; color: #111827; margin-bottom: 20px; padding-bottom: 8px; border-bottom: 2px solid #e5e7eb; }
    .stats-grid { display: grid; grid-template-columns: repeat(4, 1fr); gap: 16px; margin-bottom: 24px; }
    .stat-card { border: 1px solid #e5e7eb; border-radius: 8px; padding: 16px; text-align: center; }
    .stat-value { font-size: 32px; font-weight: 800; }
    .stat-label { font-size: 12px; color: #6b7280; margin-top: 4px; }
    .progress-bar { height: 16px; border-radius: 8px; background: #e5e7eb; overflow: hidden; margin: 16px 0; }
    .progress-fill { height: 100%; border-radius: 8px; }
    table { width: 100%; border-collapse: collapse; font-size: 13px; }
    th { background: #f9fafb; padding: 10px 12px; text-align: left; font-size: 11px; font-weight: 700; text-transform: uppercase; letter-spacing: .5px; color: #6b7280; border-bottom: 2px solid #e5e7eb; }
    .page-break { page-break-before: always; }
    @media print { .page-break { page-break-before: always; } }
  </style>
</head>
<body>

<!-- COVER PAGE -->
<div class="cover">
  <div class="cover-tag">Compliance Audit Report</div>
  <div class="cover-title">${escapeHtml(framework)}</div>
  <div class="cover-subtitle">${escapeHtml(modelName)}</div>
  <div class="cover-meta">
    <div><strong>Organization:</strong> ${escapeHtml(orgName)}</div>
    <div><strong>Report Date:</strong> ${now}</div>
    <div><strong>Generated by:</strong> ThreatForge</div>
  </div>
</div>

<!-- EXECUTIVE SUMMARY -->
<div class="section">
  <div class="section-title">Executive Summary</div>
  <div class="stats-grid">
    <div class="stat-card">
      <div class="stat-value" style="color:#1e40af">${total}</div>
      <div class="stat-label">Total Controls</div>
    </div>
    <div class="stat-card">
      <div class="stat-value" style="color:#16a34a">${covered}</div>
      <div class="stat-label">Covered</div>
    </div>
    <div class="stat-card">
      <div class="stat-value" style="color:#d97706">${partial}</div>
      <div class="stat-label">Partial</div>
    </div>
    <div class="stat-card">
      <div class="stat-value" style="color:#dc2626">${gapCount}</div>
      <div class="stat-label">Gaps</div>
    </div>
  </div>
  <div style="margin-bottom:8px;font-size:14px;font-weight:600">Overall Compliance: ${score.toFixed(1)}%</div>
  <div class="progress-bar">
    <div class="progress-fill" style="width:${Math.min(100, score)}%;background:${score >= 70 ? "#16a34a" : score >= 40 ? "#d97706" : "#dc2626"}"></div>
  </div>
</div>

<!-- GAP LIST -->
${
  criticalGaps.length > 0
    ? `
<div class="section page-break">
  <div class="section-title">Unaddressed Controls (${criticalGaps.length})</div>
  <table>
    <thead>
      <tr>
        <th style="width:100px">Control ID</th>
        <th>Control Name</th>
        <th style="width:90px">Status</th>
        <th>Recommended Actions</th>
      </tr>
    </thead>
    <tbody>
      ${criticalGaps.map(gapRow).join("")}
    </tbody>
  </table>
</div>
`
    : ""
}

${
  partialGaps.length > 0
    ? `
<div class="section page-break">
  <div class="section-title">Partially Addressed Controls (${partialGaps.length})</div>
  <table>
    <thead>
      <tr>
        <th style="width:100px">Control ID</th>
        <th>Control Name</th>
        <th style="width:90px">Status</th>
        <th>Recommended Actions</th>
      </tr>
    </thead>
    <tbody>
      ${partialGaps.map(gapRow).join("")}
    </tbody>
  </table>
</div>
`
    : ""
}

<div class="section" style="margin-top:40px;font-size:11px;color:#9ca3af;border-top:1px solid #e5e7eb;padding-top:16px">
  Generated by ThreatForge on ${now} · ${escapeHtml(framework)} compliance audit for ${escapeHtml(modelName)}
</div>

</body>
</html>`;
}
