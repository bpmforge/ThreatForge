/** Search CWEs by query */
export function searchCWEs(query: string, maxResults = 50): CWEEntry[] {
  const queryLower = query.toLowerCase();
  return CWE_DATABASE.filter((cwe) => {
    const searchText =
      `${cwe.id} ${cwe.name} ${cwe.description} ${cwe.category}`.toLowerCase();
    return searchText.includes(queryLower);
  }).slice(0, maxResults);
}

/** Get CWE count */
export function getCWECount(): number {
  return CWE_DATABASE.length;
}

/** Get all categories with counts */
export function getCWECategoryCounts(): Record<CWECategory, number> {
  const counts = {} as Record<CWECategory, number>;
  CWE_DATABASE.forEach((cwe) => {
    counts[cwe.category] = (counts[cwe.category] || 0) + 1;
  });
  return counts;
}
