/**
 * PDF template — barrel that assembles and re-exports generatePDFHTML
 */

import type { Node, Edge } from "@xyflow/react";
import type { ExportThreat } from "../../types";
import { escapeHtml } from "../download";
import { getStyles } from "./styles";
import {
  getBrandingLogo,
  getBrandingStyles,
  type ReportBranding,
} from "./branding";
import { getSummarySection } from "./cover";
import {
  getComponentsTable,
  getConnectionsTable,
  getThreatsByCategory,
  getThreatSummaryTable,
} from "./threats-section";
import { getComplianceSummary } from "./mitigations-section";

export * from "./styles";
export * from "./branding";
export * from "./cover";
export * from "./threats-section";
export * from "./mitigations-section";

/** Generate complete PDF HTML */
export function generatePDFHTML(
  modelName: string,
  nodes: Node[],
  edges: Edge[],
  threats: ExportThreat[],
  diagramDataUrl?: string,
  branding?: ReportBranding,
): string {
  const date = new Date().toLocaleDateString();

  return `<!DOCTYPE html>
<html>
<head>
  <title>${escapeHtml(modelName)} - Threat Model Report</title>
  <style>${getStyles()}</style>
  <style>${getBrandingStyles(branding)}</style>
</head>
<body>
  ${getBrandingLogo(branding)}
  <h1>${escapeHtml(modelName)}</h1>
  <p class="meta">Threat Model Report • Generated ${date}</p>
  ${getSummarySection(nodes, edges, threats)}
  ${diagramDataUrl ? `<h2>Architecture Diagram</h2><div class="diagram"><img src="${diagramDataUrl}" alt="Threat Model Diagram" /></div>` : ""}
  ${getComponentsTable(nodes)}
  ${getConnectionsTable(nodes, edges)}
  <h2>Threats by STRIDE Category</h2>
  ${getThreatsByCategory(threats)}
  ${getThreatSummaryTable(threats)}
  ${getComplianceSummary(threats)}
  <p style="margin-top: 40px; color: #9ca3af; font-size: 12px; text-align: center;">Generated by ThreatForge</p>
</body>
</html>`;
}
